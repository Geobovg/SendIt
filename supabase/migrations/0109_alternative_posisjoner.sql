from player_catalog as catalog
where card.catalog_id = catalog.id
  and cardinality(catalog.alt_positions) > 0;

create or replace function public.copy_alt_positions_to_card() returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.catalog_id is not null and cardinality(new.alt_positions) = 0 then
    select alt_positions into new.alt_positions from player_catalog where id = new.catalog_id;
    new.alt_positions := coalesce(new.alt_positions, '{}');
  end if;
  return new;
end;
$$;

create trigger manager_cards_copy_alt_positions
  before insert on manager_cards
  for each row execute function public.copy_alt_positions_to_card();
